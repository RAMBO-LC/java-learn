public class IntermidiateOp {

    public static void main(String[] args) {

        int a = 10;

        // Increment
        a++;
        System.out.println("a++ : " + a); // Output: 11

        // Increment
        ++a;
        System.out.println("++a : " + a); // Output: 12

        // Decrement
        a--;
        System.out.println("a-- : " + a); // Output: 11

        // Decrement
        --a;
        System.out.println("--a : " + a); // Output: 10

    }
}